using ComplianceService.Application.Contracts;
using ComplianceService.Application.DTOs;
using ComplianceService.Domain.Auditor;
using ComplianceService.Domain.Enums;
using ComplianceService.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace ComplianceService.Application.Services;

/// <summary>
/// Replaces legacy AuditService.generate for AIOrchestrator — creates Compliance AuditSession SSOT rows.
/// </summary>
public sealed class AuditGenerateFacadeService : IAuditGenerateFacadeService
{
    private readonly ComplianceDbContext _db;
    private readonly ILogger<AuditGenerateFacadeService> _logger;

    public AuditGenerateFacadeService(ComplianceDbContext db, ILogger<AuditGenerateFacadeService> logger)
    {
        _db = db;
        _logger = logger;
    }

    public async Task<GenerateAuditFacadeResponse> GenerateAsync(
        GenerateAuditFacadeRequest request, CancellationToken ct = default)
    {
        if (request.OrganizationId == Guid.Empty || request.ComplianceProgramId == Guid.Empty)
            throw new ArgumentException("OrganizationId and ComplianceProgramId are required.");

        var year = DateTime.UtcNow.Year;
        var count = await _db.AuditSessions.CountAsync(s => s.TenantId == request.OrganizationId, ct);
        var sessionNumber = $"AUD-{year}-{(count + 1):D4}";

        var hospitalId = request.HospitalId;
        var frameworkId = request.FrameworkId;
        if ((!hospitalId.HasValue || hospitalId == Guid.Empty) || (!frameworkId.HasValue || frameworkId == Guid.Empty))
        {
            var journey = await _db.ComplianceJourneys.AsNoTracking()
                .Where(j => j.OrganizationId == request.OrganizationId)
                .OrderByDescending(j => j.UpdatedAt)
                .FirstOrDefaultAsync(ct);
            hospitalId ??= journey?.HospitalId;
            frameworkId ??= journey?.FrameworkId;
        }

        var now = DateTime.UtcNow;
        var session = new AuditSession
        {
            Id = Guid.NewGuid(),
            TenantId = request.OrganizationId,
            HospitalId = hospitalId is { } h && h != Guid.Empty ? h : null,
            FrameworkId = frameworkId is { } f && f != Guid.Empty ? f : null,
            SessionNumber = sessionNumber,
            AuditType = request.AuditType == default ? AuditType.InternalAudit : request.AuditType,
            Scope = $"AI-generated audit for compliance program {request.ComplianceProgramId:N}",
            Status = AuditSessionStatus.Planned,
            PlannedStartDate = now,
            Summary = "Draft session generated by AI orchestrator workflow. Requires human review.",
            ComplianceProgramId = request.ComplianceProgramId,
            CreatedAt = now,
            LastUpdatedAt = now,
        };

        _db.AuditSessions.Add(session);
        await _db.SaveChangesAsync(ct);

        _logger.LogInformation(
            "Generated Compliance AuditSession {SessionId} ({SessionNumber}) for org {OrgId} program {ProgramId}",
            session.Id, session.SessionNumber, request.OrganizationId, request.ComplianceProgramId);

        return Map(session);
    }

    public async Task<GenerateAuditFacadeResponse?> GetAsync(Guid sessionId, CancellationToken ct = default)
    {
        var session = await _db.AuditSessions.AsNoTracking()
            .FirstOrDefaultAsync(s => s.Id == sessionId, ct);
        return session == null ? null : Map(session);
    }

    private static GenerateAuditFacadeResponse Map(AuditSession session) => new()
    {
        Id = session.Id,
        SessionNumber = session.SessionNumber,
        Status = session.Status.ToString(),
        OrganizationId = session.TenantId,
        ComplianceProgramId = session.ComplianceProgramId,
        StartedAt = session.PlannedStartDate ?? session.CreatedAt,
    };
}
