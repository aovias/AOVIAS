using ComplianceService.Domain.Copilot;
using ComplianceService.Domain.Copilot.Enums;

namespace ComplianceService.Application.Copilot.Contracts;

/// <summary>
/// Persistence contract for CopilotRecommendation entities.
/// No generation logic — storage and retrieval only.
/// </summary>
public interface ICopilotRecommendationRepository
{
    Task CreateAsync(CopilotRecommendation recommendation, CancellationToken cancellationToken = default);

    Task<CopilotRecommendation?> GetAsync(Guid id, CancellationToken cancellationToken = default);

    Task<IReadOnlyList<CopilotRecommendation>> SearchAsync(
        Guid organizationId,
        RecommendationStatus? status = null,
        string? persona = null,
        int page = 1,
        int pageSize = 20,
        CancellationToken cancellationToken = default);

    /// <summary>Persists an Accept state transition raised on the entity.</summary>
    Task AcceptAsync(Guid id, CancellationToken cancellationToken = default);

    /// <summary>Persists a Dismiss state transition raised on the entity.</summary>
    Task DismissAsync(Guid id, CancellationToken cancellationToken = default);

    /// <summary>Persists an Expire state transition raised on the entity.</summary>
    Task ExpireAsync(Guid id, CancellationToken cancellationToken = default);

    // ── Sprint 13B additions ─────────────────────────────────────────────────

    /// <summary>
    /// Batch-persist multiple recommendations generated by the rule engine in a single transaction.
    /// </summary>
    Task BulkCreateAsync(
        IReadOnlyList<CopilotRecommendation> recommendations,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Mark all Proposed recommendations older than <paramref name="olderThan"/> as Expired.
    /// Called by the engine after generating new recommendations to clear stale data.
    /// </summary>
    Task ExpireStaleAsync(
        Guid organizationId,
        DateTime olderThan,
        CancellationToken cancellationToken = default);

    /// <summary>Retrieve top-priority recommendations for a specific persona.</summary>
    Task<IReadOnlyList<CopilotRecommendation>> GetByPersonaAsync(
        Guid organizationId,
        string persona,
        RecommendationStatus? status = null,
        int maxCount = 5,
        CancellationToken cancellationToken = default);

    Task SaveChangesAsync(CancellationToken cancellationToken = default);
}
