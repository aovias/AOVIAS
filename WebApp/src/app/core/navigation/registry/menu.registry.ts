type NavItemInput = Omit<
  NavigationItem,
  | 'visible'
  | 'enabled'
  | 'searchable'
  | 'favoriteAllowed'
  | 'recentTracking'
  | 'breadcrumb'
  | 'surfaces'
> & {
  surfaces?: readonly NavigationSurface[];
  visible?: boolean;
  enabled?: boolean;
  searchable?: boolean;
  favoriteAllowed?: boolean;
  recentTracking?: boolean;
  breadcrumb?: boolean;
};

function navItem(input: NavItemInput): NavigationItem {
  const {
    visible = true,
    enabled = true,
    searchable = true,
    favoriteAllowed = true,
    recentTracking = true,
    breadcrumb = true,
    surfaces = ['sidebar', 'search', 'breadcrumb'] as const,
    ...rest
  } = input;
  return Object.freeze({
    ...rest,
    visible,
    enabled,
    searchable,
    favoriteAllowed,
    recentTracking,
    breadcrumb,
    surfaces,
  });
}

