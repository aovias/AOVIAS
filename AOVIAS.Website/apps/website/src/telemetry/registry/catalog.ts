export type EventRegistry = typeof eventRegistry;

export function getEventDefinition(name: EventName): EventDefinition {
  return eventRegistry[name];
}

export function listEventDefinitions(): readonly EventDefinition[] {
  return Object.values(eventRegistry);
}

export function listConversionEvents(): readonly EventDefinition[] {
  return listEventDefinitions().filter((event) => event.isConversion);
}
